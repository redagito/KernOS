static int lf(int pos, const char *file, const char *what)
{
    fprintf(stderr, "mkfont: refuse to lie: %s:%d %s\n", file, pos, what);
    return 0;
}

/* Build the full FONT_LENGTH x GLYPH_ROWS bitmap from the art tables. */
static unsigned char glyphs[FONT_LENGTH][GLYPH_ROWS];

static int build(void)
{
    int c;

    if (NPRINT != '~' - ' ' + 1)
        return lf(0, "table", "printable art must cover exactly 32..126");

    for (c = 0; c < FONT_LENGTH; ++c) {
        const char **src;
        int r;

        if (c < ' ')      src = 0;                    /* blank control  */
        else if (c <= '~') src = art + (c - ' ') * GLYPH_ROWS;
        else               src = missing;

        for (r = 0; r < GLYPH_ROWS; ++r) {
            const char *row = src ? src[r] : "........";
            unsigned char b = 0;
            int i;

            if (strlen(row) != GLYPH_COLS)
                return lf((int)(src ? (size_t)((src - art)) : 0), "art",
                          "row is not 8 chars");
            for (i = 0; i < GLYPH_COLS; ++i) {
                if (row[i] == '#')  b |= (unsigned char)(0x80 >> i);
                else if (row[i] != '.')
                    return lf(0, "art", "only '#' and '.' are art");
            }
            glyphs[c][r] = b;
        }
    }

    /* printable ASCII glyphs must have ink: a blank cell there is not
       a glyph, it is a lie about having drawn one */
    for (c = '!'; c <= '~'; ++c) {
        int r, ink = 0;
        for (r = 0; r < GLYPH_ROWS; ++r) ink |= glyphs[c][r];
        if (!ink)
            return lf(0, "art", "printable glyph is empty");
    }
    return 1;
}

static void put32(FILE *f, unsigned long v)   /* little-endian */
{
    putc((int)(v & 0xFF), f);
    putc((int)((v >> 8) & 0xFF), f);
    putc((int)((v >> 16) & 0xFF), f);
    putc((int)((v >> 24) & 0xFF), f);
}

static int emit(const char *path)
{
    FILE *f = fopen(path, "wb");
    int c, r;

    if (!f) {
        perror(path);
        return 0;
    }
    put32(f, 0x864AB552UL);          /* magic */
    put32(f, 0);                     /* version */
    put32(f, 32);                    /* headersize */
    put32(f, 0);                     /* flags */
    put32(f, FONT_LENGTH);           /* length */
    put32(f, CHARSPACE);             /* charsize */
    put32(f, GLYPH_ROWS);            /* height  */
    put32(f, GLYPH_COLS);            /* width   */
    for (c = 0; c < FONT_LENGTH; ++c)
        for (r = 0; r < GLYPH_ROWS; ++r)
            putc(glyphs[c][r], f);
    fclose(f);
    return 1;
}

static void render(const char *s)
{
    int i, r;

    for (r = 0; r < GLYPH_ROWS; ++r) {
        for (i = 0; s[i]; ++i) {
            const unsigned char *g;
            int x;

            /* (unsigned char) range can't exceed 255: no >= check */
            if ((int)(unsigned char)s[i] < ' ') {
                fputs("..", stdout);
                putchar(' ');
                continue;
            }
            g = glyphs[(unsigned char)s[i]];
            for (x = 0; x < GLYPH_COLS; ++x)
                putchar((g[r] & (0x80 >> x)) ? '#' : '.');
            putchar(' ');
        }
        putchar('\n');
    }
}

int main(int argc, char **argv)
{
    if (argc == 3 && strcmp(argv[1], "--render") == 0) {
        if (!build()) return 1;
        render(argv[2]);
        return 0;
    }
    if (argc == 3 && strcmp(argv[1], "--out") == 0) {
        if (!build()) return 1;
        return emit(argv[2]) ? 0 : 1;
    }
    fprintf(stderr, "usage: mkfont --out FILE | --render TEXT\n");
    return 2;
}
