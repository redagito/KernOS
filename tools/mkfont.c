/*
 * mkfont — KernOS font assembler (host tool, never runs in the kernel).
 *
 * The M5.7 console font is HAND-DRAWN in this file: one 8x16 ASCII-art
 * cell per printable glyph ('#' = pixel on, '.' = off). mkfont turns
 * the art into a PSF2 file (the standard console-font container — no
 * custom format) at build/font.psf2, which the kernel image embeds via
 * an .incbin object; kernel/arch/x86_64/fbcon.c parses and validates
 * the same header at boot.
 *
 * PSF2 header (www.win.tue.nl/~aeb/linux/kbd/font-formats-3.html),
 * little-endian u32s: magic 0x864AB552, version, headersize, flags,
 * length (glyph count), charsize (bytes/glyph), height, width.
 *
 * Honesty rules:
 *   - every art cell is EXACTLY 8 chars wide, 16 rows; mkfont refuses
 *     to write a PSF2 for anything malformed;
 *   - every printable ASCII glyph must have ink;
 *   - controls (0..31) are blank; 127..255 get an outlined "missing"
 *     placeholder box (visible, honest, named in the docs).
 *
 * --render "KernOS" prints the sample string as art on stdout: the
 * font is reviewable on the host BEFORE any boot depends on it.
 */

